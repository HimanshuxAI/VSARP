        created_at,
        updated_at,
        last_sign_in_at,
        email_confirmed_at,
        confirmation_sent_at,
        confirmation_token,
        recovery_token,
        email_change_token_new,
        email_change
    )
    values (
        p_user_id,
        '00000000-0000-0000-0000-000000000000',
        'authenticated',
        'authenticated',
        p_user_email,
        '{"provider":"email","providers":["email"]}'::jsonb,
        metadata,
        false,
        crypt(p_user_password, gen_salt('bf')),
        now(),
        now(),
        now(),
        now(),
        now(),
        '',
        '',
        '',
        ''
    );

    insert into auth.identities (
        id,
        provider_id,
        provider,
        user_id,
        identity_data,
        last_sign_in_at,
        created_at,
        updated_at
    )
    values (
        p_user_id,
        p_user_id::text,
        'email',
        p_user_id,
        jsonb_build_object(
            'sub', p_user_id::text,
            'email', p_user_email,
            'email_verified', true
        ),
        now(),
        now(),
        now()
    );

    update public.profiles
    set
        email = p_user_email,
        full_name = p_user_name,
        role = p_user_role,
        student_id = p_user_student_id,
        department = p_user_department,
        phone = p_user_phone,
        skills = p_user_skills,
        status = p_user_status
    where id = p_user_id;
end;
$$;

create or replace function public.is_role(role_names text[])
returns boolean
language sql
stable
security definer
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role = any(role_names)
    );
$$;

create or replace function public.guard_profile_updates()
returns trigger
language plpgsql
as $$
begin
    if auth.uid() = old.id and not public.is_role(array['admin']) then
        if new.role is distinct from old.role
            or new.status is distinct from old.status
            or new.email is distinct from old.email
            or new.student_id is distinct from old.student_id
            or new.department is distinct from old.department then
            raise exception 'You are not allowed to change protected profile fields.';
        end if;
    end if;

    return new;
end;
$$;

create trigger profiles_guard_updates
before update on public.profiles
for each row
execute procedure public.guard_profile_updates();

create or replace function public.notify_students_about_drive()
returns trigger
language plpgsql
security definer
as $$
begin
    insert into public.placement_notifications (
        profile_id,
        drive_id,
        title,
        message,
        notification_type
    )
    select
        profile.id,
        new.id,
        new.company_name || ' drive is live',
        new.role_offered || ' applications are now open. Apply before ' ||
            coalesce(to_char(new.application_deadline, 'DD Mon YYYY'), to_char(new.drive_date, 'DD Mon YYYY')) || '.',
        'placement_drive'
    from public.profiles profile
    where profile.role = 'student'
      and profile.status = 'active';

    return new;
end;
$$;

